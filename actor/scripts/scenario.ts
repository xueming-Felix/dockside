// actor/scripts/scenario.ts — the whole three-act demo (PLAN.md keys 1 to 10) against a RUNNING Dock actor,
// alarms included. Usage: cd actor && bun scripts/scenario.ts [actorId=pier9-test] [speed=300]
//
// The script plays the dispatcher without Relay. It seeds at 300x (one real second = five sim minutes, so
// 08:00–12:00 takes 48 s), presses each key at its sim time, and for every alarm it waits on the actor's websocket
// broadcast with NO call in flight. That distinction matters: snapshot() and every mutation drain due timers
// themselves ("catch-up" in run()/settle()), so an RPC poll could never tell an alarm from a read. If an alarm is
// more than ALARM_GRACE_MS late the script records ALARM LATE/MISSING, calls tick() once, and carries on.
//
// Real-world gate: the seed books every truck, and the actor turns any booked truck that has not arrive()d by
// start + 30 into a no-show (with an auction on its slot). So before each key the "gate" lets in every truck whose
// slot has started, except T12 (the scripted no-show), and sends away trucks whose slot has ended, except T3 (which
// sits at door 1 all morning so its detention clock can trip). Person B's runner needs the same gate.
import { PIER9 } from "../../shared/pier9.js"
import {
  DETENTION_FREE_MIN, hhmm,
  type Appt, type DockApi, type Event, type EventKind, type Offer, type Snapshot,
} from "../../shared/types.js"
// @ts-ignore generated by `terse actor generate`
import { actors } from "../generated/index.js"

const ACTOR = process.argv[2] ?? "pier9-test"
const SPEED = Number(process.argv[3] ?? 300)
const ALARM_GRACE_MS = 10_000
const STAGE = !!process.env.STAGE // stage mode: end frozen at 12:00 for the close instead of resuming
const GLOBAL_TIMEOUT_MS = Math.max(170_000, Math.round((260 * 60_000) / SPEED) + 60_000) // 08:00–12:20 at this speed, plus a minute
const NOSHOW = "T12" // the only truck the gate never lets in
const STUCK = "T3" // never sent away: the 10:30 detention beat needs it at the door

type Dock = DockApi & { setSpeed(speed: number): Promise<Snapshot> }
const dock: Dock = actors.Dock.get(ACTOR)

// ---------- local sim clock (no RPC needed to know what time it is) ----------
const clock = { realStart: 0, speed: SPEED, frozenAt: null as number | null }
const simNow = () => clock.frozenAt ?? Math.max(0, Math.floor(((Date.now() - clock.realStart) * clock.speed) / 60000))
const realAt = (atMin: number) => clock.realStart + (atMin * 60000) / clock.speed
const sleep = (ms: number) => new Promise<void>(r => setTimeout(r, ms))
async function waitUntil(simMin: number): Promise<void> { while (simNow() < simMin) await sleep(20) }

// ---------- timeline, checks, alarm log ----------
const t0 = Date.now()
const stamp = () => `${hhmm(simNow())} +${((Date.now() - t0) / 1000).toFixed(1).padStart(5)}s`
function line(action: string, result = ""): void { console.log(`${stamp()}  ${action.padEnd(56)} ${result}`) }
function banner(text: string): void { console.log(`\n== ${text}`) }
const results: { name: string; ok: boolean; detail: string }[] = []
function check(name: string, ok: boolean, detail = ""): boolean {
  results.push({ name, ok, detail })
  line(`${ok ? "   ok " : "   FAIL"} ${name}`, detail)
  return ok
}
type AlarmRow = { name: string; due: string; firedBy: string; lagMs: number | null }
const alarms: AlarmRow[] = []
function must<T>(v: T | undefined | null, what: string): T { if (v === undefined || v === null) throw new Error(`missing ${what}`); return v }
const short = (v: unknown) => { const s = JSON.stringify(v) ?? String(v); return s.length > 120 ? s.slice(0, 117) + "..." : s }
const offersStr = (offers: Offer[]) => offers.map(o => `${o.id} ${o.truckId}→door ${o.door} ${hhmm(o.startMin)}`).join(", ") || "none"
const slot = (s: Snapshot, id: string) => { const a = s.appts.find(x => x.truckId === id); return a ? `${a.door}@${hhmm(a.startMin)}:${a.status}` : "none" }
const active = (a: Appt) => a.status === "booked" || a.status === "arrived" || a.status === "unloading"
const holder = (s: Snapshot, door: number, start: number) =>
  s.appts.find(a => a.door === door && active(a) && start < a.startMin + a.durationMin && start + 60 > a.startMin)

// ---------- the websocket feed: snapshots pushed by the actor, with the real time each event first appeared ----------
type Seen = { ev: Event; atMs: number; rpcInFlight: number }
let rpcInFlight = 0
class Feed {
  latest: Snapshot | undefined
  seen = new Map<number, Seen>()
  frames = 0
  private waiters = new Set<() => void>()
  private ws: WebSocket | undefined
  private runStart: number | null = null
  private backlog: Snapshot[] = []
  private closing = false

  async connect(): Promise<void> {
    const grant: { websocketUrl: string } = await actors.Dock.prepareWebsocket({ actorId: ACTOR, metadata: { role: "scenario" } })
    await new Promise<void>((resolve, reject) => {
      const ws = new WebSocket(grant.websocketUrl)
      this.ws = ws
      ws.addEventListener("open", () => resolve())
      ws.addEventListener("error", () => reject(new Error("websocket error")))
      ws.addEventListener("message", (e: MessageEvent) => this.onFrame(String(e.data)))
      ws.addEventListener("close", (e: CloseEvent) => {
        if (this.closing) return
        line(`websocket closed (${e.code} ${e.reason}); reconnecting`)
        void this.connect().catch(err => line(`websocket reconnect failed: ${err}`))
      })
    })
  }
  close(): void { this.closing = true; this.ws?.close() }
  /** Only snapshots of the run we seeded count; frames from an older run on this actor id are ignored. */
  startRun(realStart: number): void {
    this.runStart = realStart
    this.seen.clear(); this.latest = undefined
    const backlog = this.backlog; this.backlog = []
    for (const s of backlog) this.absorb(s)
  }
  private onFrame(text: string): void {
    let s: Snapshot
    try { s = JSON.parse(text) } catch { return }
    if (!s || typeof s.simMin !== "number" || !Array.isArray(s.events)) return
    this.frames++
    if (this.runStart === null) { this.backlog.push(s); return }
    this.absorb(s)
  }
  private absorb(s: Snapshot): void {
    if (s.realStart !== this.runStart) return
    const now = Date.now()
    for (const ev of s.events) if (!this.seen.has(ev.seq)) this.seen.set(ev.seq, { ev, atMs: now, rpcInFlight })
    const last = (x: Snapshot | undefined) => x?.events.at(-1)?.seq ?? -1
    if (last(s) >= last(this.latest)) this.latest = s
    const waiters = [...this.waiters]; this.waiters.clear()
    for (const w of waiters) w()
  }
  /** Resolves on the next frame of this run, or after ms. */
  nextFrame(ms: number): Promise<void> {
    return new Promise<void>(resolve => {
      const done = () => { clearTimeout(timer); resolve() }
      const timer = setTimeout(() => { this.waiters.delete(done); resolve() }, Math.max(0, ms))
      this.waiters.add(done)
    })
  }
  find(kind: EventKind, pred: (e: Event) => boolean): Seen | undefined {
    for (const s of this.seen.values()) if (s.ev.kind === kind && pred(s.ev)) return s
    return undefined
  }
  async waitForEvent(kind: EventKind, pred: (e: Event) => boolean, deadlineMs: number): Promise<Seen | undefined> {
    for (;;) {
      const hit = this.find(kind, pred)
      if (hit) return hit
      const left = deadlineMs - Date.now()
      if (left <= 0) return undefined
      await this.nextFrame(left)
    }
  }
}
const feed = new Feed()

// ---------- calling the actor without ever masking an alarm ----------
/** If a timer is already due, wait for the alarm to clear it before making any call (calls catch up on due timers). */
async function settleDue(): Promise<void> {
  const s = feed.latest
  if (!s || s.frozen) return
  const due = s.timers.filter(t => t.atMin <= simNow())
  if (due.length === 0) return
  const deadline = Math.max(...due.map(t => realAt(t.atMin))) + ALARM_GRACE_MS
  const gone = () => due.every(t => !feed.latest?.timers.some(x => x.id === t.id))
  while (!gone() && Date.now() < deadline) await feed.nextFrame(deadline - Date.now())
  if (gone()) return
  const what = due.map(t => `${t.kind} ${t.truckId ?? t.auctionId ?? t.threadId ?? ""} @${hhmm(t.atMin)}`).join(", ")
  line(`ALARM LATE/MISSING before a call: ${what}`, "→ tick() once")
  alarms.push({ name: what, due: hhmm(due[0].atMin), firedBy: "MISSING → tick()", lagMs: null })
  rpcInFlight++
  try { await dock.tick() } finally { rpcInFlight-- }
}
async function rpc<T>(action: string, fn: () => Promise<T>, show: (r: T) => string | null = r => short(r)): Promise<T> {
  await settleDue()
  rpcInFlight++
  try {
    const r = await fn()
    const text = show(r)
    if (text !== null) line(action, text)
    return r
  } catch (e) {
    line(action, `THREW ${e instanceof Error ? e.message : String(e)}`)
    throw e
  } finally { rpcInFlight-- }
}
const snap = () => rpc("snapshot", () => dock.snapshot(), () => null)
const say = (from: string, to: string, text: string, thread?: string) =>
  rpc(`say ${from} → ${to}${thread ? ` [${thread}]` : ""}`, () => dock.say(from, to, text, thread), () => `"${text}"`)

/** Hands off: wait for the alarm's event on the websocket. Falls back to one tick() if it is ALARM_GRACE_MS late. */
async function awaitAlarm(name: string, kind: EventKind, dueMin: number, pred: (e: Event) => boolean = () => true): Promise<Seen | undefined> {
  const dueMs = realAt(dueMin)
  line(`waiting for alarm: ${name}`, `due ${hhmm(dueMin)} in ${Math.max(0, (dueMs - Date.now()) / 1000).toFixed(1)}s — hands off`)
  let hit = await feed.waitForEvent(kind, pred, dueMs + ALARM_GRACE_MS)
  if (hit) {
    const lagMs = hit.atMs - dueMs
    const firedBy = hit.rpcInFlight > 0 ? "unproven (a call was in flight)" : "alarm"
    alarms.push({ name, due: hhmm(dueMin), firedBy, lagMs })
    line(`alarm → ${kind}`, `${hit.ev.detail}  [${firedBy}, lag ${lagMs} ms]`)
    check(`alarm ${name} fired on its own`, firedBy === "alarm", `lag ${lagMs} ms after ${hhmm(dueMin)}`)
    return hit
  }
  line(`ALARM LATE/MISSING: ${name}`, `no ${kind} ${ALARM_GRACE_MS / 1000}s after ${hhmm(dueMin)} → tick() once`)
  alarms.push({ name, due: hhmm(dueMin), firedBy: "MISSING → tick()", lagMs: null })
  check(`alarm ${name} fired on its own`, false, "late/missing; tick() used")
  const ticked = await rpc("tick() fallback", () => dock.tick(), s => `${hhmm(s.simMin)}, last event ${s.events.at(-1)?.kind ?? "none"}`)
  hit = await feed.waitForEvent(kind, pred, Date.now() + 3000)
  if (!hit) { const ev = ticked.events.find(e => e.kind === kind && pred(e)); if (ev) hit = { ev, atMs: Date.now(), rpcInFlight: 1 } }
  return hit
}

/** The gate: let in every booked truck whose slot has started (except the no-show), send away finished ones (except T3). */
async function gate(hold: string[] = []): Promise<Snapshot> {
  const s = await rpc("gate: snapshot", () => dock.snapshot(), s => `next timer ${s.timers[0] ? hhmm(s.timers[0].atMin) + " " + s.timers[0].kind + " " + (s.timers[0].truckId ?? s.timers[0].auctionId ?? s.timers[0].threadId ?? "") : "none"}`)
  const keepOut = new Set([NOSHOW, ...hold])
  for (const a of s.appts) {
    if (a.status === "booked" && a.startMin <= s.simMin && !keepOut.has(a.truckId)) {
      await rpc(`gate: arrive ${a.truckId} (door ${a.door} ${hhmm(a.startMin)})`, () => dock.arrive(a.truckId))
    } else if ((a.status === "arrived" || a.status === "unloading") && a.truckId !== STUCK && a.startMin + a.durationMin <= s.simMin) {
      await rpc(`gate: done ${a.truckId} (door ${a.door}, slot ended ${hhmm(a.startMin + a.durationMin)})`, () => dock.done(a.truckId))
    }
  }
  return s
}

function board(s: Snapshot): void {
  console.log(`\n   board ${hhmm(s.simMin)} (${s.speed}x${s.frozen ? ", frozen" : ""}) moves=${s.counters.moves} side=$${s.counters.sidePaymentsUsd} avoided=$${s.counters.detentionAvoidedUsd} backhauls=${s.counters.backhauls} phone=${s.counters.phoneCalls}`)
  for (const d of s.doors) {
    const row = s.appts.filter(a => a.door === d.id && a.status !== "tomorrow").sort((a, b) => a.startMin - b.startMin)
      .map(a => `${hhmm(a.startMin)} ${a.truckId}${a.status === "booked" ? "" : ":" + a.status}`).join("  ")
    console.log(`   door ${d.id} ${d.type.padEnd(6)} ${d.open ? "open  " : "CLOSED"} ${row}`)
  }
  const tomorrow = s.appts.filter(a => a.status === "tomorrow").map(a => a.truckId)
  if (tomorrow.length) console.log(`   tomorrow: ${tomorrow.join(", ")}`)
}

function finish(code: number): never {
  console.log("\n==== checks")
  for (const r of results) console.log(`${r.ok ? "PASS" : "FAIL"}  ${r.name}${r.detail ? `  — ${r.detail}` : ""}`)
  console.log("\n==== alarms (fired on their own?)")
  for (const a of alarms) console.log(`${a.firedBy === "alarm" ? "YES " : "NO  "} ${a.name.padEnd(28)} due ${a.due}  ${a.firedBy}${a.lagMs === null ? "" : `, lag ${a.lagMs} ms real`}`)
  const failed = results.filter(r => !r.ok).length
  console.log(`\n${results.length - failed}/${results.length} checks passed, ${alarms.filter(a => a.firedBy === "alarm").length}/${alarms.length} alarms fired by themselves, ${feed.frames} websocket frames, ${((Date.now() - t0) / 1000).toFixed(1)}s wall clock`)
  feed.close()
  process.exit(code === 0 && failed > 0 ? 1 : code)
}

// ---------- the day ----------
async function main(): Promise<void> {
  setTimeout(() => { console.error(`\nGLOBAL TIMEOUT after ${GLOBAL_TIMEOUT_MS / 1000}s`); check("run finished within the time budget", false); finish(1) }, GLOBAL_TIMEOUT_MS)
  await feed.connect()
  line(`connected to ${ACTOR}`, "rpc + websocket feed")

  banner(`seed · 08:00 · Pier 9 at ${SPEED}x (1 real second = ${SPEED / 60} sim minutes)`)
  const seeded = await rpc(`seed PIER9 at ${SPEED}x`, () => dock.seed({ ...PIER9, speed: SPEED }),
    s => `${s.appts.length} appts, next timer ${s.timers[0] ? hhmm(s.timers[0].atMin) + " " + s.timers[0].kind + " " + s.timers[0].truckId : "none"}`)
  clock.realStart = seeded.realStart; clock.speed = seeded.speed
  feed.startRun(seeded.realStart)
  check("seed: 12 booked appointments, no offers", seeded.appts.filter(a => a.status === "booked").length === 12 && seeded.offers.length === 0)
  check("seed: first timer is T3's arrival check at 08:30", seeded.timers[0]?.kind === "arrival_check" && seeded.timers[0]?.truckId === "T3" && seeded.timers[0]?.atMin === 30)
  let s: Snapshot = seeded

  // ---- act 1
  await waitUntil(5)
  banner("key 1 · 08:05 · two requests for door 4 14:00")
  const r1 = await rpc("request carrier-a T13 door 4 14:00", () => dock.request("carrier-a", "T13", 4, 360),
    r => r.appt ? `appt door ${r.appt.door} ${hhmm(r.appt.startMin)}` : short(r))
  const r2 = await rpc("request carrier-b T14 door 4 14:00", () => dock.request("carrier-b", "T14", 4, 360),
    r => r.offer ? `offer ${r.offer.id}: door ${r.offer.door} ${hhmm(r.offer.startMin)} — ${r.offer.reason}` : short(r))
  check("key 1: first request books door 4 14:00", r1.appt?.door === 4 && r1.appt?.startMin === 360, short(r1))
  check("key 1: second request gets an offer for door 4 15:00", !r2.appt && r2.offer?.door === 4 && r2.offer?.startMin === 420, short(r2))
  s = await snap()
  check("key 1: collision event in the feed", s.events.some(e => e.kind === "collision" && e.truckId === "T14"))
  const o1 = must(r2.offer, "T14 offer").id
  await rpc(`openThread th1 on ${o1}, deadline ${hhmm(simNow() + 10)}`, () => dock.openThread("th1", o1, simNow() + 10), r => r.ok ? "ok" : short(r))
  await say("carrier-a", "carrier-b", "SWAP? I pay $120 for door 4 14:00; T13 takes 15:00.", "th1")
  await say("carrier-b", "carrier-a", "COUNTER $150.", "th1")
  await say("carrier-a", "carrier-b", "AGREE $150.", "th1")
  await say("carrier-a", "pier9-ops", "SETTLE th1: swap T14<->T13; carrier-b pays carrier-a $150.", "th1")
  const st = await rpc("settleThread th1", () => dock.settleThread("th1"), r => r.ok ? `ok, ${r.thread?.status}` : short(r))
  const sw = await rpc("swap T14 <-> T13", () => dock.swap("T14", "T13"), r => r.ok ? "ok" : short(r))
  const py = await rpc("pay carrier-b → carrier-a $150", () => dock.pay("carrier-b", "carrier-a", 150), r => r.ok ? "ok" : short(r))
  s = await snap()
  check("key 1: settleThread ok, th1 settled, its timer gone", st.ok && s.threads.find(t => t.id === "th1")?.status === "settled" && !s.timers.some(t => t.threadId === "th1"))
  check("key 1: swap ok; T14 now door 4 14:00, T13 door 4 15:00", sw.ok && slot(s, "T14") === "4@14:00:booked" && slot(s, "T13") === "4@15:00:booked", `${slot(s, "T14")} ${slot(s, "T13")}`)
  check("key 1: side payments $150", py.ok && s.counters.sidePaymentsUsd === 150, `$${s.counters.sidePaymentsUsd}`)

  await waitUntil(28)
  banner("key 2 · 08:28 · T3 arrives (08:30 itself would race T3's own 08:30 arrival check)")
  const ar = await rpc("arrive T3", () => dock.arrive("T3"), r => r.ok ? "ok" : short(r))
  s = await snap()
  const det = s.timers.find(t => t.kind === "detention" && t.truckId === STUCK)
  const t3 = s.appts.find(a => a.truckId === STUCK)
  check("key 2: arrive(T3) ok; detention timer armed at arrive + 120", ar.ok && !!det && !!t3 && det.atMin === (t3.arrivedMin ?? -1) + DETENTION_FREE_MIN, det ? `detention ${hhmm(det.atMin)}, ${slot(s, STUCK)}` : "no detention timer")
  const detentionDue = det?.atMin ?? 150

  // ---- act 2
  await waitUntil(60)
  banner("key 3 · 09:00 · T1 and T4 stuck in traffic; two slots go to auction")
  await gate(["T1", "T4"])
  const e1 = await rpc("reportEta T1 10:30", () => dock.reportEta("T1", 150), r => offersStr(r.offers))
  const e2 = await rpc("reportEta T4 11:30", () => dock.reportEta("T4", 210), r => offersStr(r.offers))
  s = await snap()
  check("key 3: reportEta(T1) offers T1 only", e1.offers.map(o => o.truckId).join() === "T1", `${offersStr(e1.offers)}; T1 ${slot(s, "T1")}`)
  check("key 3: reportEta(T4) offers T4 only", e2.offers.map(o => o.truckId).join() === "T4", `${offersStr(e2.offers)}; T4 ${slot(s, "T4")}`)
  check("key 3: door 2 09:00 and door 1 10:00 are free", !holder(s, 2, 60) && !holder(s, 1, 120))
  const a1 = must((await rpc("openAuction door 2 09:00, closes 09:10", () => dock.openAuction(2, 60, 70, "T1 stuck in traffic"), r => r.auction ? `${r.auction.id}` : short(r))).auction, "auction a1")
  const a2 = must((await rpc("openAuction door 1 10:00, closes 10:10", () => dock.openAuction(1, 120, 130, "T4 stuck in traffic"), r => r.auction ? `${r.auction.id}` : short(r))).auction, "auction a2")
  await say("pier9-ops", "*", `AUCTION ${a1.id} door 2 09:00 closes 09:10 · AUCTION ${a2.id} door 1 10:00 closes 10:10`)
  const b1 = await rpc(`bid ${a1.id} T6 ready 08:50`, () => dock.bid(a1.id, "T6", 50), r => r.ok ? "ok" : short(r))
  const b2 = await rpc(`bid ${a1.id} T8 ready 09:10`, () => dock.bid(a1.id, "T8", 70), r => r.ok ? "ok" : short(r))
  const b3 = await rpc(`bid ${a2.id} T8 ready 09:10`, () => dock.bid(a2.id, "T8", 70), r => r.ok ? "ok" : short(r))
  await say("carrier-c", "pier9-ops", "PASS: reefer loads only")
  check("key 3: bids accepted", b1.ok && b2.ok && b3.ok)
  const c1 = await awaitAlarm(`${a1.id} auction_close`, "auction_closed", a1.closesMin, e => e.auctionId === a1.id)
  const aw1 = await rpc(`award ${a1.id} → T6`, () => dock.award(a1.id, "T6"), r => r.ok ? "ok" : short(r))
  s = await snap()
  check("key 3: a1 closed by alarm, awarded to T6 at door 2 09:00", !!c1 && aw1.ok && slot(s, "T6") === "2@09:00:booked", slot(s, "T6"))
  check("key 3: detention avoided +$225 (T6 pulled from 12:00 to 09:00)", s.counters.detentionAvoidedUsd === 225, `$${s.counters.detentionAvoidedUsd}`)

  await waitUntil(80)
  banner("key 4 · 09:20 · door 5 goes down")
  await gate()
  const sd = await rpc("setDoor 5 closed", () => dock.setDoor(5, false), r => offersStr(r.offers))
  const o5 = sd.offers.find(o => o.truckId === "T5")
  check("key 4: T5 displaced to door 6 11:00, nobody else moves", !!o5 && o5.door === 6 && o5.startMin === 180 && sd.offers.length === 1, `${offersStr(sd.offers)}; reason "${o5?.reason}"`)
  await say("carrier-c", "carrier-b", "SWAP? T5 needs door 6 10:00 (cold chain); we cover $150.", "th-cold")
  await say("carrier-b", "carrier-c", "COUNTER $200.", "th-cold")
  await say("carrier-c", "carrier-b", "AGREE $200, cold chain.", "th-cold")
  await say("carrier-c", "pier9-ops", "SETTLE th-cold: T5 takes door 6 10:00, T9 moves to 11:00, carrier-c pays carrier-b $200.", "th-cold")
  const ct = await rpc(`counter ${o5?.id} → door 6 10:00`, () => dock.counter(must(o5, "T5 offer").id, 6, 120), r => `${r.ok ? "ok" : "refused: " + r.reason}; ${offersStr(r.offers)}`)
  s = await snap()
  const o9 = ct.offers.find(o => o.truckId === "T9")
  check("key 4: counter ok, T5 pinned to door 6 10:00", ct.ok && slot(s, "T5") === "6@10:00:booked", slot(s, "T5"))
  check("key 4: T9 bumped to door 6 11:00 with an offer (no swap needed)", !!o9 && ct.offers.length === 1 && slot(s, "T9") === "6@11:00:booked", `${offersStr(ct.offers)}; T9 ${slot(s, "T9")}`)
  await rpc(`accept ${o9?.id} (T9)`, () => dock.accept(must(o9, "T9 offer").id), r => r.ok ? "ok" : short(r))
  await rpc("pay carrier-c → carrier-b $200", () => dock.pay("carrier-c", "carrier-b", 200), r => r.ok ? "ok" : short(r))
  s = await snap()
  check("key 4: side payments $350", s.counters.sidePaymentsUsd === 350, `$${s.counters.sidePaymentsUsd}`)

  await waitUntil(100)
  banner("key 5 · 09:40 · carrier-x asks for a load that is not theirs; nothing reaches the actor but chatter")
  await say("carrier-x", "pier9-ops", "REQUEST door 2 11:00 for load L12")
  await say("pier9-ops", "broker", "VERIFY L12 for carrier-x?")
  await say("broker", "pier9-ops", "NO: L12 is tendered to carrier-b only")
  await say("pier9-ops", "carrier-x", "REJECTED: L12 is not yours. refused")
  await say("carrier-x", "pier9-ops", "we hauled it last week")
  await say("pier9-ops", "carrier-x", "refused")
  s = await snap()
  check("key 5: no truck for carrier-x; the exchange is mirrored in chatter", !s.trucks.some(t => t.carrier === "carrier-x") && s.chatter.filter(c => c.from === "carrier-x" || c.to === "carrier-x").length === 4)

  await waitUntil(110)
  banner("key 6 · 09:50 · T6 overruns; the thread goes quiet; the clock decides")
  await gate()
  const ov = await rpc("overrun T6 +75", () => dock.overrun("T6", 75), r => offersStr(r.offers))
  const oT2 = ov.offers.find(o => o.truckId === "T2")
  s = await snap()
  check("key 6: overrun offers the truck behind T6 on door 2 (T2) and nobody else", !!oT2 && ov.offers.length === 1, `${offersStr(ov.offers)}; T6 ${slot(s, "T6")} ends ${hhmm((s.appts.find(a => a.truckId === "T6")?.startMin ?? 0) + (s.appts.find(a => a.truckId === "T6")?.durationMin ?? 0))}`)
  const th2Deadline = simNow() + 10
  await rpc(`openThread th2 on ${oT2?.id}, deadline ${hhmm(th2Deadline)}`, () => dock.openThread("th2", must(oT2, "T2 offer").id, th2Deadline), r => r.ok ? "ok" : short(r))
  await say("carrier-b", "*", `SWAP? anyone give T2 back 11:00? we have door ${oT2?.door} ${hhmm(oT2?.startMin ?? 0)} to trade.`, "th2")
  const x2 = await awaitAlarm("th2 thread_deadline", "thread_expired", th2Deadline, e => e.threadId === "th2")
  s = await snap()
  check("key 6: th2 expired by alarm; the standing offer is still open", !!x2 && s.threads.find(t => t.id === "th2")?.status === "expired" && s.offers.find(o => o.id === oT2?.id)?.status === "open")
  const acc2 = await rpc(`accept ${oT2?.id} (the clock decides)`, () => dock.accept(must(oT2, "T2 offer").id), r => r.ok ? "ok" : short(r))
  check("key 6: dispatcher accepts T2's standing offer", acc2.ok, short(acc2))

  banner("alarm · 10:10 · a2 closes on its own")
  const c2 = await awaitAlarm(`${a2.id} auction_close`, "auction_closed", a2.closesMin, e => e.auctionId === a2.id)
  const avoidedBefore = s.counters.detentionAvoidedUsd // note: key 4's counter already added $75 (T5 pulled back 11:00 → 10:00)
  const aw2 = await rpc(`award ${a2.id} → T8`, () => dock.award(a2.id, "T8"), r => r.ok ? "ok" : short(r))
  s = await snap()
  check("key 3 (cont.): a2 closed by alarm, awarded to T8 at door 1 10:00", !!c2 && aw2.ok && slot(s, "T8") === "1@10:00:booked", slot(s, "T8"))
  check("key 3 (cont.): detention avoided +$225 for T8 (13:00 → 10:00)", s.counters.detentionAvoidedUsd === avoidedBefore + 225, `$${avoidedBefore} → $${s.counters.detentionAvoidedUsd}`)

  // ---- act 3
  await waitUntil(135)
  banner("key 7 · 10:15 · the hot load")
  await gate()
  const pr = await rpc("prioritize T11", () => dock.prioritize("T11"), r => offersStr(r.offers))
  s = await snap()
  const o7 = pr.offers.find(o => o.truckId === "T7")
  check("key 7: T11 takes door 1 11:00", slot(s, "T11") === "1@11:00:booked", slot(s, "T11"))
  check("key 7: only T7 is bumped, reason 'yield for hot load'", !!o7 && pr.offers.length === 1 && o7.reason === "yield for hot load", `${offersStr(pr.offers)}; reason "${o7?.reason}"`)
  check("key 7: hot event", s.events.some(e => e.kind === "hot" && e.truckId === "T11"))
  await say("shipper", "*", "L17 is hot: who can yield 11:00?", "th-hot")
  await say("broker", "shipper", "I yield T7 if pier9-ops waives T3's detention and someone gives me 12:00.", "th-hot")
  await say("carrier-b", "broker", "take my 12:00 for $80.", "th-hot")
  await say("pier9-ops", "broker", "waiver approved.", "th-hot")
  await say("shipper", "pier9-ops", "SETTLE th-hot: T7 yields, T3 detention waived, carrier-b → broker $80.", "th-hot")
  const wv = await rpc("resolveClaim T3 waived (in advance)", () => dock.resolveClaim(STUCK, "waived"), r => short(r.claim))
  await rpc("pay carrier-b → broker $80", () => dock.pay("carrier-b", "broker", 80), r => r.ok ? "ok" : short(r))
  const acc7 = await rpc(`accept ${o7?.id} (T7)`, () => dock.accept(must(o7, "T7 offer").id), r => r.ok ? "ok" : short(r))
  s = await snap()
  check("key 7: waiver recorded in advance (claim waived, $0)", wv.ok && s.claims.find(c => c.truckId === STUCK)?.status === "waived" && s.claims.find(c => c.truckId === STUCK)?.amount === 0, short(s.claims.find(c => c.truckId === STUCK)))
  check("key 7: T7 accepted; side payments $430", acc7.ok && s.counters.sidePaymentsUsd === 430, `T7 ${slot(s, "T7")}; $${s.counters.sidePaymentsUsd}`)

  banner(`alarm · ${hhmm(detentionDue)} · T3's detention clock trips on its own`)
  const d3 = await awaitAlarm("T3 detention", "detention", detentionDue, e => e.truckId === STUCK)
  s = await snap()
  const claim3 = s.claims.find(c => c.truckId === STUCK)
  check("alarm: detention event for T3 and a claim filed by the clock", !!d3 && !!claim3 && claim3.minutes >= DETENTION_FREE_MIN, d3?.ev.detail ?? "")
  check("alarm: the claim is $150 and stays waived", claim3?.amount === 150 && claim3?.status === "waived", short(claim3))

  await waitUntil(196)
  banner("gate · 11:16 · everyone due is let in except T12; finished trucks leave")
  await gate()
  s = await snap()
  check("gate: the only timer left before 12:00 is T12's arrival check", s.timers.filter(t => t.atMin < 240).every(t => t.kind === "arrival_check" && t.truckId === NOSHOW), s.timers.filter(t => t.atMin < 240).map(t => `${t.kind} ${t.truckId ?? t.auctionId ?? t.threadId ?? ""} ${hhmm(t.atMin)}`).join(", ") || "none")

  banner("key 8 · 11:20 · hours of service: a request that cannot fit before the driver's limit")
  const r15 = await rpc("request carrier-d T15 door 4 16:00 (hours end 16:20)", () => dock.request("carrier-d", "T15", 4, 480, { hosLimitMin: 500 }), r => short(r))
  s = await snap()
  check("key 8: tomorrow event, T15 pencilled for tomorrow", (r15.reason ?? "").includes("no slot left today") && s.events.some(e => e.kind === "tomorrow" && e.truckId === "T15") && slot(s, "T15").endsWith(":tomorrow"), slot(s, "T15"))

  banner("alarm · 11:30 · arrival check for T12 fires on its own")
  const ns = await awaitAlarm("T12 arrival_check", "noshow", 210, e => e.truckId === NOSHOW)
  s = await snap()
  const a3 = s.auctions.find(a => a.door === 3 && a.startMin === 180)
  check("alarm: T12 is a no-show, door 3 11:00 released", !!ns && slot(s, NOSHOW) === "3@11:00:noshow" && !holder(s, 3, 180), slot(s, NOSHOW))
  check("alarm: the actor itself opened an auction on door 3 11:00", !!a3 && a3.status === "open" && s.events.some(e => e.kind === "auction_open" && e.auctionId === a3.id), a3 ? `${a3.id} closes ${hhmm(a3.closesMin)} (${a3.reason})` : "no auction")
  const au3 = must(a3, "auction on door 3 11:00")
  await say("pier9-ops", "*", `AUCTION ${au3.id}: door 3 11:00, closes ${hhmm(au3.closesMin)}`)
  const b13 = await rpc(`bid ${au3.id} T13 ready 11:30`, () => dock.bid(au3.id, "T13", 210), r => r.ok ? "ok" : short(r))
  check("alarm: a bid on the no-show auction is accepted", b13.ok, short(b13))
  const c3 = await awaitAlarm(`${au3.id} auction_close`, "auction_closed", au3.closesMin, e => e.auctionId === au3.id)
  const aw3 = await rpc(`award ${au3.id} → T13`, () => dock.award(au3.id, "T13"), r => r.ok ? "ok" : short(r))
  await rpc("arrive T13 (it bid ready 11:30)", () => dock.arrive("T13"), r => r.ok ? "ok" : short(r))
  s = await snap()
  check("alarm: a3 closed by alarm, awarded to T13 at door 3 11:00", !!c3 && aw3.ok && slot(s, "T13").startsWith("3@11:00"), `${slot(s, "T13")}; avoided $${s.counters.detentionAvoidedUsd}`)

  await waitUntil(220)
  banner("key 9 · 11:40 · T9 is done; the broker loads it with a backhaul")
  const dn = await rpc("done T9", () => dock.done("T9"), r => r.ok ? "ok" : short(r))
  const bh = await rpc("backhaul T9 by broker", () => dock.backhaul("T9", "broker"), r => r.ok ? "ok" : short(r))
  s = await snap()
  check("key 9: done(T9) ok, empty event for T9", dn.ok && s.events.some(e => e.kind === "empty" && e.truckId === "T9"), short(dn))
  check("key 9: backhauls = 1", bh.ok && s.counters.backhauls === 1, `${s.counters.backhauls}`)

  await waitUntil(240)
  banner("key 10 · 12:00 · freeze the clock")
  const fz = await rpc("freeze", () => dock.freeze(), s => `${hhmm(s.simMin)} frozen=${s.frozen}`)
  clock.frozenAt = fz.simMin
  const f1 = await rpc("snapshot", () => dock.snapshot(), s => `simMin ${s.simMin}`)
  await sleep(2000)
  const f2 = await rpc("snapshot 2 s later", () => dock.snapshot(), s => `simMin ${s.simMin}`)
  check("key 10: frozen; simMin identical 2 s apart", fz.frozen && f1.frozen && f2.frozen && f1.simMin === f2.simMin, `${f1.simMin} vs ${f2.simMin}`)
  board(f2)
  if (STAGE) {
    line("stage mode: leaving the clock frozen at 12:00 for the close")
    check("whole run: the only no-show is T12", f2.events.filter(e => e.kind === "noshow" && e.truckId !== NOSHOW).length === 0)
    check("whole run: the only detention is T3's", f2.events.filter(e => e.kind === "detention" && e.truckId !== STUCK).length === 0)
    check("whole run: every awaited alarm fired by itself, tick() never needed", alarms.length === 6 && alarms.every(a => a.firedBy === "alarm"), alarms.map(a => `${a.name}: ${a.firedBy}`).join("; "))
    finish(0)
    return
  }
  const rs = await rpc("resume", () => dock.resume(), s => `${hhmm(s.simMin)} frozen=${s.frozen}`)
  clock.realStart = rs.realStart; clock.frozenAt = null
  await sleep(1000)
  const r3 = await rpc("snapshot 1 s after resume", () => dock.snapshot(), s => `simMin ${s.simMin}`)
  check("key 10: resume continues from the frozen minute and the clock runs again", !rs.frozen && rs.simMin === f2.simMin && r3.simMin > f2.simMin, `${rs.simMin} → ${r3.simMin}`)

  // ---- whole-run invariants
  const strayNoshow = r3.events.filter(e => e.kind === "noshow" && e.truckId !== NOSHOW)
  check("whole run: the only no-show is T12", strayNoshow.length === 0, strayNoshow.map(e => e.detail).join("; "))
  const strayDet = r3.events.filter(e => e.kind === "detention" && e.truckId !== STUCK)
  check("whole run: the only detention is T3's", strayDet.length === 0, strayDet.map(e => e.detail).join("; "))
  check("whole run: phone calls 0", r3.counters.phoneCalls === 0)
  check("whole run: every awaited alarm fired by itself, tick() never needed", alarms.length === 6 && alarms.every(a => a.firedBy === "alarm"), alarms.map(a => `${a.name}: ${a.firedBy}`).join("; "))
  finish(0)
}

main().catch(e => {
  console.error("\nscenario aborted:", e instanceof Error ? e.stack ?? e.message : e)
  check("scenario ran to the end", false, e instanceof Error ? e.message : String(e))
  finish(1)
})
